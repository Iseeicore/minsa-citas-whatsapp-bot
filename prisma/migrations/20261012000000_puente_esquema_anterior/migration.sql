    UPDATE chatbot.incidencia_paciente i
       SET medidas_tomadas = n.medidas_tomadas,
           fundamento = n.fundamento,
           resultado_resolucion_id = n.resultado_resolucion_id,
           motivo_archivo_id = n.motivo_archivo_id,
