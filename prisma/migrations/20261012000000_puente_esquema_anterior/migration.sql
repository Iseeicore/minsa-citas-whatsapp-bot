           derivado_en = n.derivado_en,
           derivado_por = n.derivado_por,
           tomado_en = n.tomado_en,
           tomado_por = n.tomado_por,
           area_destino_id = n.area_destino_id
      FROM (
        SELECT p.id,
               CASE
                 WHEN p.resolucion IS NULL THEN NULL
                 WHEN char_length(btrim(p.resolucion)) >= 10 THEN p.resolucion
                 ELSE 'Resolución registrada: ' || btrim(p.resolucion)
               END AS medidas_tomadas,
               CASE WHEN p.resolucion IS NOT NULL
                    THEN 'No registrado: la resolución es anterior al registro separado de medidas tomadas, fundamento y resultado.'
               END AS fundamento,
               CASE WHEN p.resolucion IS NOT NULL
                    THEN (SELECT id FROM catalogo.resultado_resolucion WHERE codigo = 'ATENDIDO')
               END AS resultado_resolucion_id,
               CASE
                 WHEN p.estado_incidencia_id <> 7 THEN NULL
                 WHEN p.resolucion IS NOT NULL THEN (SELECT id FROM catalogo.motivo_archivo WHERE codigo = 'RESUELTA_VIGENCIA')
                 ELSE (SELECT id FROM catalogo.motivo_archivo WHERE codigo = 'VENCIDA_SIN_ATENDER')
               END AS motivo_archivo_id,
               CASE WHEN p.estado_incidencia_id = 7 THEN coalesce(h7.fecha_hora, p.fecha_modificacion) END AS archivado_en,
               h6.fecha_hora AS derivado_en,
               h6.actor AS derivado_por,
               h3.fecha_hora AS tomado_en,
               h3.actor AS tomado_por,
               CASE WHEN c.es_sensible THEN v_otrans END AS area_destino_id
          FROM chatbot.incidencia_paciente p
          LEFT JOIN catalogo.categoria_incidencia c ON c.id = p.categoria_id
          LEFT JOIN LATERAL (
            SELECT a.fecha_hora, a.actor
              FROM chatbot.incidencia_paciente_auditoria a
             WHERE a.incidencia_paciente_id = p.id AND a.operacion = 'ACTUALIZACION'
               AND a.cambios -> 'estado_incidencia_id' ->> 'despues' = '6'
             ORDER BY a.id DESC
             LIMIT 1
          ) h6 ON true
          LEFT JOIN LATERAL (
            SELECT a.fecha_hora, a.actor
              FROM chatbot.incidencia_paciente_auditoria a
             WHERE a.incidencia_paciente_id = p.id AND a.operacion = 'ACTUALIZACION'
               AND a.cambios -> 'estado_incidencia_id' ->> 'despues' = '3'
             ORDER BY a.id DESC
             LIMIT 1
          ) h3 ON true
          LEFT JOIN LATERAL (
            SELECT a.fecha_hora
              FROM chatbot.incidencia_paciente_auditoria a
             WHERE a.incidencia_paciente_id = p.id AND a.operacion = 'ACTUALIZACION'
               AND a.cambios -> 'estado_incidencia_id' ->> 'despues' = '7'
             ORDER BY a.id DESC
             LIMIT 1
          ) h7 ON true
      ) n
     WHERE n.id = i.id
       AND (n.medidas_tomadas, n.fundamento, n.resultado_resolucion_id, n.motivo_archivo_id, n.archivado_en,
            n.derivado_en, n.derivado_por, n.tomado_en, n.tomado_por, n.area_destino_id)
           IS DISTINCT FROM
           (i.medidas_tomadas, i.fundamento, i.resultado_resolucion_id, i.motivo_archivo_id, i.archivado_en,
            i.derivado_en, i.derivado_por, i.tomado_en, i.tomado_por, i.area_destino_id);

    ALTER TABLE chatbot.incidencia_paciente ENABLE TRIGGER trg_incidencia_paciente_a_reglas;
