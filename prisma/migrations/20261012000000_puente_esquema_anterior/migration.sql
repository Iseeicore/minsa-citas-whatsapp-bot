CREATE OR REPLACE FUNCTION public.fn_limitar_usuarios_establecimiento() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  v_tope CONSTANT integer := 3;
  v_activos integer;
BEGIN
  IF NOT NEW.activo OR NEW.area_id IS NULL THEN
    RETURN NEW;
  END IF;
  IF TG_OP = 'UPDATE' AND NEW.area_id IS NOT DISTINCT FROM OLD.area_id AND NEW.activo = OLD.activo AND NEW.eliminado_en IS NOT DISTINCT FROM OLD.eliminado_en THEN
    RETURN NEW;
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM catalogo.area a JOIN catalogo.tipo_area ta ON ta.id = a.tipo_area_id
     WHERE a.id = NEW.area_id AND ta.codigo = 'ESTABLECIMIENTO'
  ) THEN
    RETURN NEW;
  END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended('usuario_interno:tope:' || NEW.area_id::text, 0));
  SELECT count(*) INTO v_activos FROM gestion.usuario_interno WHERE area_id = NEW.area_id AND activo AND id <> NEW.id;
  IF v_activos >= v_tope THEN
    RAISE EXCEPTION 'usuario_interno: el establecimiento ya tiene 3 usuarios activos'
      USING ERRCODE = 'check_violation',
            HINT = 'Desactive a un usuario del establecimiento antes de agregar o reactivar otro.';
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION chatbot.archivar_incidencias_vencidas(p_dias integer DEFAULT 3, p_lote integer DEFAULT 1000)
RETURNS integer
LANGUAGE plpgsql AS $$
DECLARE
  v_archivadas integer;
BEGIN
  IF p_dias IS NULL OR p_dias < 1 THEN
    RAISE EXCEPTION 'archivar_incidencias_vencidas: los dias deben ser al menos 1'
      USING ERRCODE = 'check_violation';
  END IF;
  IF p_lote IS NULL OR p_lote < 1 THEN
    RAISE EXCEPTION 'archivar_incidencias_vencidas: el lote debe ser al menos 1'
      USING ERRCODE = 'check_violation';
  END IF;

  PERFORM set_config('app.actor', 'sistema:vencimiento', true);

  UPDATE chatbot.incidencia_paciente
     SET estado_incidencia_id = 7
   WHERE id IN (
     SELECT id
       FROM chatbot.incidencia_paciente
      WHERE estado_incidencia_id IN (1, 2, 3, 6)
        AND activo
        AND coalesce(reabierto_en, fecha_creacion) < now() - make_interval(days => p_dias)
      ORDER BY coalesce(reabierto_en, fecha_creacion)
      LIMIT p_lote
        FOR UPDATE SKIP LOCKED
   );
  GET DIAGNOSTICS v_archivadas = ROW_COUNT;
  RETURN v_archivadas;
END;
$$;

CREATE OR REPLACE FUNCTION chatbot.barrer_archivos_huerfanos(p_lote integer DEFAULT 1000)
RETURNS TABLE (ruta text)
LANGUAGE plpgsql AS $$
DECLARE
  v_ids uuid[];
BEGIN
  IF p_lote IS NULL OR p_lote < 1 THEN
    RAISE EXCEPTION 'barrer_archivos_huerfanos: el lote debe ser al menos 1'
      USING ERRCODE = 'check_violation';
  END IF;

  PERFORM set_config('app.actor', 'sistema:barrido', true);

  v_ids := ARRAY(
    SELECT id
      FROM chatbot.solicitud_carga
     WHERE incidencia_paciente_id IS NULL
       AND cerrada_en IS NULL
       AND vence_en < now()
     ORDER BY vence_en
     LIMIT p_lote
       FOR UPDATE SKIP LOCKED
  );
  IF coalesce(cardinality(v_ids), 0) = 0 THEN
    RETURN;
  END IF;

  UPDATE chatbot.archivo_recibido
     SET estado_archivo_id = 4, motivo_rechazo = 'sesión vencida'
   WHERE solicitud_carga_id = ANY (v_ids) AND estado_archivo_id IN (1, 2);

  UPDATE chatbot.solicitud_carga SET cerrada_en = now() WHERE id = ANY (v_ids);

  RETURN QUERY
    SELECT a.ruta_cuarentena
      FROM chatbot.archivo_recibido a
     WHERE a.solicitud_carga_id = ANY (v_ids) AND a.evidencia_id IS NULL;
END;
$$;

