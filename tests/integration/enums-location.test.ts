function rootEnumFiles(): string[] {
  return fs
    .readdirSync(ENUMS_FOLDER, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".ts"))
    .map((entry) => entry.name);
}

describe("ubicación de los enums", () => {
  it("ningún enum nuevo se crea en la raíz de lib/enums: va en lib/enums/<dominio>/", () => {
    expect(rootEnumFiles().filter((file) => !ROOT_ENUMS_PENDING_MOVE.has(file))).toEqual([]);
  });

  it("http-status.ts se queda en la raíz de lib/enums", () => {
    expect(rootEnumFiles()).toContain("http-status.ts");
  });
});
